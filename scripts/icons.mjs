/** Vendor a small, licensed subset; runtime works without a CDN or npm resolver. */
import { readFile, writeFile, mkdir } from "node:fs/promises";
const aliases = {
  video: "video",
  eye: "eye",
  copy: "copy",
  file: "file-text",
  search: "search",
  bookmark: "bookmark",
  comment: "message-circle",
  repeat: "repeat-2",
  heart: "heart",
  share: "share-2",
  chart: "chart-no-axes-column",
  more: "ellipsis",
  back: "arrow-left",
  arrowUp: "arrow-up",
  arrowDown: "arrow-down",
  folder: "folder",
  chevron: "chevron-right",
  globe: "globe",
  settings: "settings-2",
  check: "check",
  close: "x",
  clock: "clock",
  verified: "badge-check",
  plus: "plus",
  info: "info",
  trash: "trash-2",
  tag: "tag",
  move: "folder-input",
  refresh: "refresh-cw",
  external: "external-link",
  archive: "archive",
  layers: "layers",
  pointer: "mouse-pointer-2",
  threads: "list-tree",
  shield: "shield-check",
  logo: "bookmark-check",
  link: "link",
  download: "download",
  arrowRight: "arrow-right",
  circleCheck: "circle-check",
};
const nodes = {};
for (const [name, file] of Object.entries(aliases)) {
  const svg = await readFile(
    `node_modules/lucide-static/icons/${file}.svg`,
    "utf8",
  );
  nodes[name] = svg
    .match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)[1]
    .trim()
    .replace(/\s+/g, " ");
}
const brands = {};
for (const name of ["x", "reddit", "xiaohongshu", "zhihu"]) {
  const svg = await readFile(
    `node_modules/simple-icons/icons/${name}.svg`,
    "utf8",
  );
  brands[name] = svg
    .match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)[1]
    .replace(/<title>.*?<\/title>/g, "");
}
await writeFile(
  "app/icon-data.js",
  "// Generated by scripts/icons.mjs. Lucide ISC/MIT; Simple Icons CC0. See licenses/.\nexport const nodes=" +
    JSON.stringify(nodes, null, 2) +
    ";\nexport const brands=" +
    JSON.stringify(brands, null, 2) +
    ";\n",
);
await mkdir("licenses", { recursive: true });
await writeFile(
  "licenses/Lucide.txt",
  await readFile("node_modules/lucide-static/LICENSE"),
);
await writeFile(
  "licenses/Simple-Icons.txt",
  await readFile("node_modules/simple-icons/LICENSE.md"),
);
await writeFile(
  "licenses/Simple-Icons-disclaimer.md",
  await readFile("node_modules/simple-icons/DISCLAIMER.md"),
);
const mark = nodes.logo;
await writeFile(
  "assets/app-icon.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><defs><linearGradient id="bg" x2="1" y2="1"><stop stop-color="#3c9eaa"/><stop offset="1" stop-color="#254f79"/></linearGradient></defs><rect width="1024" height="1024" rx="230" fill="url(#bg)"/><rect x="24" y="24" width="976" height="976" rx="210" fill="none" stroke="#ffffff44" stroke-width="12"/><g transform="translate(218 210) scale(24.5)" fill="none" stroke="white" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${mark}</g></svg>`,
);
console.log("Vendored Lucide and Simple Icons, with licenses.");
